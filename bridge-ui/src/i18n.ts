const dicts: Record<Lang, Dict> = { en, th, 'zh-Hans': zhHans, 'zh-Hant': zhHant }

export function translate(lang: Lang, key: Key): string {
  return dicts[lang][key] ?? en[key]
}

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('ark.lang') as Lang | null
    if (saved && saved in dicts) return saved
  } catch {
    // storage blocked
  }
  const nav = navigator.language.toLowerCase()
  if (nav.startsWith('th')) return 'th'
  if (nav.startsWith('zh')) return nav.includes('tw') || nav.includes('hk') || nav.includes('hant') ? 'zh-Hant' : 'zh-Hans'
  return 'en'
}

export const LangContext = createContext<Lang>('en')

export function useT() {
  const lang = useContext(LangContext)
  return (key: Key) => translate(lang, key)
}
